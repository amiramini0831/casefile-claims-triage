-- Casefile domain schema: policies and their current claims.
--
-- Apply with scripts/setup_database.py, which runs this file against the
-- domain database as the loader user. Rows come from
-- data/raw/insurance_claims.csv after the loader's transformations; nothing
-- in these two tables is synthetic except the derived columns marked below.
--
-- CHECK constraint names are unique per database in MySQL, hence the table
-- prefix on every constraint.

CREATE TABLE IF NOT EXISTS policies (
    policy_number         INT UNSIGNED           NOT NULL,
    policy_state          CHAR(2)                NOT NULL,
    policy_start_date     DATE                   NOT NULL
        COMMENT 'Derived: incident_date minus months_as_customer',
    months_as_customer    SMALLINT UNSIGNED      NOT NULL,
    csl_per_person        INT UNSIGNED           NOT NULL
        COMMENT 'Bodily injury limit per person, USD',
    csl_per_accident      INT UNSIGNED           NOT NULL
        COMMENT 'Bodily injury limit per accident, USD',
    policy_deductible     INT UNSIGNED           NOT NULL
        COMMENT 'USD',
    policy_annual_premium DECIMAL(10, 2)         NOT NULL
        COMMENT 'USD',
    umbrella_limit        INT UNSIGNED           NOT NULL
        COMMENT 'USD, 0 = no umbrella coverage',
    insured_age           TINYINT UNSIGNED       NOT NULL
        COMMENT 'Age at the incident date',
    insured_sex           ENUM('MALE', 'FEMALE') NOT NULL,
    auto_make             VARCHAR(32)            NOT NULL,
    auto_model            VARCHAR(32)            NOT NULL,
    auto_year             SMALLINT UNSIGNED      NOT NULL,
    PRIMARY KEY (policy_number),
    CONSTRAINT chk_policies_csl
        CHECK (csl_per_accident >= csl_per_person),
    CONSTRAINT chk_policies_premium
        CHECK (policy_annual_premium > 0),
    CONSTRAINT chk_policies_age
        CHECK (insured_age BETWEEN 16 AND 110),
    -- Written without subtraction: unsigned subtraction raises on a negative
    -- result instead of evaluating the check.
    CONSTRAINT chk_policies_age_at_start
        CHECK (insured_age * 12 >= months_as_customer + 16 * 12),
    CONSTRAINT chk_policies_auto_year
        CHECK (auto_year BETWEEN 1900 AND 2100)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS claims (
    claim_id                    VARCHAR(20)       NOT NULL
        COMMENT 'Generated by the loader, e.g. CLM-2015-00001',
    policy_number               INT UNSIGNED      NOT NULL,
    incident_date               DATE              NOT NULL,
    incident_type               ENUM(
        'Single Vehicle Collision',
        'Multi-vehicle Collision',
        'Vehicle Theft',
        'Parked Car'
    )                                             NOT NULL,
    collision_type              ENUM(
        'Front Collision',
        'Rear Collision',
        'Side Collision'
    )                                             NULL
        COMMENT 'NULL = not applicable (theft, parked car)',
    incident_severity           ENUM(
        'Trivial Damage',
        'Minor Damage',
        'Major Damage',
        'Total Loss'
    )                                             NOT NULL,
    authorities_contacted       ENUM(
        'Police',
        'Fire',
        'Ambulance',
        'Other',
        'None'
    )                                             NOT NULL
        COMMENT 'None is a real category, not a missing value',
    police_report_available     BOOLEAN           NULL
        COMMENT 'NULL = unknown',
    incident_state              CHAR(2)           NOT NULL,
    incident_city               VARCHAR(64)       NOT NULL,
    incident_location           VARCHAR(128)      NOT NULL,
    incident_hour_of_the_day    TINYINT UNSIGNED  NOT NULL,
    number_of_vehicles_involved TINYINT UNSIGNED  NOT NULL,
    witnesses                   TINYINT UNSIGNED  NOT NULL,
    total_claim_amount          DECIMAL(12, 2)    NOT NULL COMMENT 'USD',
    injury_claim                DECIMAL(12, 2)    NOT NULL COMMENT 'USD',
    property_claim              DECIMAL(12, 2)    NOT NULL COMMENT 'USD',
    vehicle_claim               DECIMAL(12, 2)    NOT NULL COMMENT 'USD',
    -- Computed by the database so the flags can never disagree with the
    -- amounts.
    has_injury                  BOOLEAN
        GENERATED ALWAYS AS (injury_claim > 0) STORED NOT NULL,
    has_property_damage         BOOLEAN
        GENERATED ALWAYS AS (property_claim > 0) STORED NOT NULL,
    PRIMARY KEY (claim_id),
    KEY idx_claims_policy_date (policy_number, incident_date),
    CONSTRAINT fk_claims_policy
        FOREIGN KEY (policy_number) REFERENCES policies (policy_number)
        ON DELETE RESTRICT
        ON UPDATE RESTRICT,
    CONSTRAINT chk_claims_amounts_non_negative
        CHECK (
            injury_claim >= 0
            AND property_claim >= 0
            AND vehicle_claim >= 0
        ),
    CONSTRAINT chk_claims_total_is_sum
        CHECK (
            total_claim_amount = injury_claim + property_claim + vehicle_claim
        ),
    CONSTRAINT chk_claims_collision_type_applies
        CHECK (
            (collision_type IS NULL)
            = (incident_type IN ('Vehicle Theft', 'Parked Car'))
        ),
    CONSTRAINT chk_claims_vehicle_count
        CHECK (
            (incident_type = 'Multi-vehicle Collision'
                AND number_of_vehicles_involved >= 2)
            OR (incident_type <> 'Multi-vehicle Collision'
                AND number_of_vehicles_involved = 1)
        ),
    CONSTRAINT chk_claims_hour
        CHECK (incident_hour_of_the_day BETWEEN 0 AND 23)
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_0900_ai_ci;
